package com.commerce.auth.notification;

import org.springframework.boot.autoconfigure.condition.ConditionalOnProperty;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.http.MediaType;
import org.springframework.http.client.SimpleClientHttpRequestFactory;
import org.springframework.stereotype.Component;
import org.springframework.web.client.RestClient;

import java.net.URI;
import java.time.Duration;
import java.util.Locale;

@Component
@ConditionalOnProperty(prefix = "careertrack.notification", name = "enabled", havingValue = "true", matchIfMissing = false)
public final class HttpVerificationNotificationClient implements VerificationNotificationClient {

    private static final long TOKEN_EXPIRY_HOURS = 24;
    private final RestClient restClient;
    private final String internalApiKey;
    private final String verificationPageUrl;

    public HttpVerificationNotificationClient(
            RestClient.Builder restClientBuilder,
            @Value("${careertrack.notification.base-url:http://localhost:8082}") String serviceUrl,
            @Value("${careertrack.notification.internal-api-key:}") String apiKey,
            @Value("${careertrack.notification.verification-page-url:http://localhost:3000/verify-email}") String pageUrl
    ) {
        if (apiKey == null || apiKey.length() < 32) {
            throw new IllegalStateException("NOTIFICATION_INTERNAL_API_KEY must contain at least 32 characters");
        }
        checkUrl(serviceUrl, "Notification service URL", true);
        checkUrl(pageUrl, "Verification page URL", false);
        this.internalApiKey = apiKey;
        this.verificationPageUrl = pageUrl;

        SimpleClientHttpRequestFactory requestFactory = new SimpleClientHttpRequestFactory();
        requestFactory.setConnectTimeout(Duration.ofSeconds(2));
        requestFactory.setReadTimeout(Duration.ofSeconds(4));
        this.restClient = restClientBuilder.baseUrl(serviceUrl)
                .requestFactory(requestFactory)
                .build();
    }

    @Override
    public void send(String email, String username, String rawToken) {
        // Generated by Auth Service: URL-safe Base64 without padding.
        if (rawToken == null || !rawToken.matches("[A-Za-z0-9_-]{43}")) {
            throw new IllegalArgumentException("Invalid verification token format");
        }
        String link = verificationPageUrl + "#token=" + rawToken;
        VerificationEmailPayload payload = new VerificationEmailPayload(
                email, username, link, TOKEN_EXPIRY_HOURS);
        restClient.post()
                .uri("/internal/notifications/email-verification")
                .contentType(MediaType.APPLICATION_JSON)
                .header("X-Internal-Api-Key", internalApiKey)
                .body(payload)
                .retrieve()
                .toBodilessEntity();
    }

    private static void checkUrl(String value, String name, boolean allowPrivateDockerHost) {
        URI uri;
        try {
            uri = URI.create(value);
        } catch (IllegalArgumentException ex) {
            throw new IllegalStateException(name + " is invalid");
        }
        String scheme = uri.getScheme() == null ? "" : uri.getScheme().toLowerCase(Locale.ROOT);
        String host = uri.getHost() == null ? "" : uri.getHost().toLowerCase(Locale.ROOT);
        boolean local = host.equals("localhost") || host.equals("127.0.0.1");
        // Single-label Docker service names resolve only within the private Compose network.
        boolean privateDockerHost = allowPrivateDockerHost && host.matches("[a-z0-9-]+")
                && !host.equals("localhost");
        if (host.isBlank() || !(scheme.equals("https") || (scheme.equals("http") && (local || privateDockerHost)))
                || uri.getUserInfo() != null || uri.getRawQuery() != null || uri.getRawFragment() != null) {
            throw new IllegalStateException(name + " must be HTTPS (HTTP allowed only for localhost or a private Docker service name), without query/fragment");
        }
    }

}
